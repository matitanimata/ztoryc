#!/usr/bin/env python3
"""Regenerates the *.inc files of the harness from the real sources, so the
harness always tests the code that ships:
  stock_fill.inc     calcFillRow / threshTone / fillRow from toonzlib/fill.cpp
  ztoryc_pass1.inc   the region search of the Toonz Raster brush Auto Fill
                     (toonzrasterbrushtool.cpp, ToonzRasterBrushTool::leftButtonUp)
Run from anywhere; paths are relative to this file."""
import os, re, sys
here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, '..', '..', 'toonz', 'sources')

def block(text, start):
    a = text.index(start)
    b = text.index('\n}\n', a) + 3
    return text[a:b]

fill = open(os.path.join(src, 'toonzlib', 'fill.cpp')).read()
parts = [block(fill, 'bool calcFillRow(const TRasterCM32P &r'),
         block(fill, 'inline int threshTone'),
         block(fill, 'void fillRow(const TRasterCM32P &r')]
# fillRow's ink-autopaint branch needs the palette; the harness has none.
parts[2] = re.sub(r'if \(palette && pix->isPurePaint\(\)\) \{.*?\n      \}\n', '',
                  parts[2], flags=re.S)
open(os.path.join(here, 'stock_fill.inc'), 'w').write('\n'.join(parts))

brush = open(os.path.join(src, 'tnztools', 'toonzrasterbrushtool.cpp')).read()
a = brush.index('std::vector<uint8_t> exterior(sw * sh, 0);')
b = brush.index('// Determine fill style from tool option.')
c = brush.index('auto inStroke = [&](int ax, int ay) {')
d = brush.index('AutoFillLineSplit::addInnerLinePixels', c)
d = brush.rindex('\n          }\n', c, d) + len('\n          }\n')
open(os.path.join(here, 'ztoryc_pass1.inc'), 'w').write(
    '// GENERATED by extract.py from toonzrasterbrushtool.cpp - do not edit\n'
    'std::vector<int> ztorycPass1(TRasterCM32P ras, int x0, int y0, int sw, int sh,\n'
    '                             TRect strokeBox, bool haveStrokeBox) {\n'
    + brush[a:b] + brush[c:d] + '\n  return toFill;\n}\n')
print('ok')
